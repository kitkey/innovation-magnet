export const hasGuide = (m: ScenarioCard["method"]) => m !== "free";
export const methodName = (m: ScenarioCard["method"]) => (m === "free" ? "свободный" : METHODS[m].name);

/** Справочник метода: короткие страницы с переключением, не простыня. Закрывается Esc, крестиком или кликом мимо; диалог не трогает. */
export function MethodGuide({ method, onClose }: { method: ScenarioCard["method"]; onClose: () => void }) {
  const [i, setI] = useState(0);
  const m = method === "free" ? null : METHODS[method];
  const n = m?.pages.length ?? 0;
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") onClose();
      else if (e.key === "ArrowRight") setI((x) => Math.min(n - 1, x + 1));
      else if (e.key === "ArrowLeft") setI((x) => Math.max(0, x - 1));
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [n, onClose]);
  if (!m) return null;
  const p = m.pages[i];
  return (
    <div className="mguide" role="dialog" aria-modal="true" aria-label={`Метод ${m.name}`} onClick={(e) => { if (e.target === e.currentTarget) onClose(); }}>
      <div className="mg-in">
        <div className="mg-h">
          <span className="mg-t"><Icon name="book" size={18} />Метод {m.name}</span>
          <span className="mg-n num">{i + 1} / {n}</span>
          <button className="ghost icon" aria-label="Закрыть" title="Закрыть (Esc)" onClick={onClose}><Icon name="x" /></button>
        </div>
        <div className="mg-steps" aria-hidden="true">{m.pages.map((_, k) => <button key={k} tabIndex={-1} className={k <= i ? "on" : ""} onClick={() => setI(k)} />)}</div>
        <div className="mg-body" key={i}>
          <span className="caps">{p.kicker}</span>
          <h3>{p.title}</h3>
          {p.body}
          {p.labels && <div className="marks mg-marks"><span className="mg-lab">Метка в разметке хода:</span>{p.labels.map((l) => <span key={l.t} className={`lab ${l.bad ? "bad" : ""}`}>{l.t}</span>)}</div>}
          {p.say && <div className="mg-say"><span className="caps">Как сказать</span>{p.say.map((q) => <p key={q}><q>{q}</q></p>)}</div>}
          {p.sayBad && <div className="mg-say bad"><span className="caps">Так не надо</span>{p.sayBad.map((q) => <p key={q}><q>{q}</q></p>)}</div>}
        </div>
        <div className="mg-foot">
          <button className="ghost" disabled={i === 0} onClick={() => setI(i - 1)}><Icon name="back" size={16} />Назад</button>
          {i < n - 1
            ? <button className="primary" onClick={() => setI(i + 1)}>Продолжить<Icon name="arrow" size={16} /></button>
            : <button className="primary" onClick={onClose}>Вернуться к диалогу</button>}
        </div>
      </div>
    </div>
  );
}
