/** Подпись поля с кнопкой «?»: по нажатию под подписью раскрывается подсказка. */
export function FieldLabel({ label, help }: { label: string; help?: string }) {
  const [open, setOpen] = useState(false);
  if (!help) return <>{label}</>;
  return (
    <>
      <span className="flabel">
        {label}
        <button type="button" className={`ftip ${open ? "on" : ""}`} aria-label={`Подсказка: ${label}`} aria-expanded={open}
          onClick={(e) => { e.preventDefault(); setOpen(!open); }}><Icon name="ask" size={16} /></button>
      </span>
      {open && <small className="fhint">{help}</small>}
    </>
  );
}

