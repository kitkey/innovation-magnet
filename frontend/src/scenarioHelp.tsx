/** Справка «Как заполнить сценарий»: те же шаги с индикатором, что у справочника метода в диалоге. */
export function ScenarioHelp({ onClose }: { onClose: () => void }) {
  const [i, setI] = useState(0);
  const n = PAGES.length;
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") onClose();
      else if (e.key === "ArrowRight") setI((x) => Math.min(n - 1, x + 1));
      else if (e.key === "ArrowLeft") setI((x) => Math.max(0, x - 1));
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [n, onClose]);
  const p = PAGES[i];
  return (
    <div className="mguide" role="dialog" aria-modal="true" aria-label="Как заполнить сценарий" onClick={(e) => { if (e.target === e.currentTarget) onClose(); }}>
      <div className="mg-in">
        <div className="mg-h">
          <span className="mg-t"><Icon name="book" size={18} />Как заполнить сценарий</span>
          <span className="mg-n num">{i + 1} / {n}</span>
          <button className="ghost icon" aria-label="Закрыть" title="Закрыть (Esc)" onClick={onClose}><Icon name="x" /></button>
        </div>
        <div className="mg-steps" aria-hidden="true">{PAGES.map((_, k) => <button key={k} tabIndex={-1} className={k <= i ? "on" : ""} onClick={() => setI(k)} />)}</div>
        <div className="mg-body" key={i}>
          <span className="caps">{p.kicker}</span>
          <h3>{p.title}</h3>
          {p.body}
        </div>
        <div className="mg-foot">
          <button className="ghost" disabled={i === 0} onClick={() => setI(i - 1)}><Icon name="back" size={16} />Назад</button>
          {i < n - 1
            ? <button className="primary" onClick={() => setI(i + 1)}>Продолжить<Icon name="arrow" size={16} /></button>
            : <button className="primary" onClick={onClose}>Вернуться к форме</button>}
        </div>
      </div>
    </div>
  );
}
